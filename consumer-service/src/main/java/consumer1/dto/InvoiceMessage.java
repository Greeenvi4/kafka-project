package consumer1.dto;

import lombok.Data;
import java.time.LocalDateTime;

/**
 * DTO для передачи сообщений о счетах (инвойсах)
 * между сервисами через систему обмена сообщениями.
 *
 * <p>Данный класс используется для сериализации/десериализации данных при
 * передаче через очереди сообщений (например, RabbitMQ, Kafka) и содержит
 * основную информацию о финансовом документе.</p>
 *
 * <p>Поля класса соответствуют основным атрибутам счета и позволяют
 * отслеживать его жизненный цикл в системе.</p>
 *
 * @author Andrus Gregory
 */
@Data
public class InvoiceMessage {
    /**
     * Уникальный идентификатор счета в базе данных.
     * Генерируется автоматически при создании записи.
     */
    private Long id;

    /**
     * Номер лицевого счета или идентификатор клиента,
     * которому принадлежит данный счет.
     *
     * <p>Формат: обычно цифровой код, но может содержать буквенные префиксы
     * в зависимости от системы учета.</p>
     */
    private String accountNumber;

    /**
     * Сумма счета-фактуры в базовой валюте системы.
     *
     * <p>Значение всегда положительное.</p>
     */
    private Double amount;

    /**
     * Текущий статус обработки счета-фактуры.
     *
     * <p>Возможные значения:</p>
     * <ul>
     *   <li><b>CREATED</b> - счет создан</li>
     *   <li><b>SENT</b> - отправлен клиенту</li>
     *   <li><b>PAID</b> - оплачен</li>
     *   <li><b>OVERDUE</b> - просрочен</li>
     *   <li><b>CANCELLED</b> - отменен</li>
     * </ul>
     */
    private String status;

    /**
     * Дата и время создания счета-фактуры в системе.
     *
     * <p>Время сохраняется в UTC и автоматически проставляется при создании
     * записи через {@code @CreationTimestamp} или аналогичную аннотацию.</p>
     *
     * <p>Формат: ISO-8601 (yyyy-MM-dd'T'HH:mm:ss.SSSZ)</p>
     */
    private LocalDateTime createdAt;
}