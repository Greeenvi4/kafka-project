package producer1.dto;

import lombok.Data;

/**
 * DTO (Data Transfer Object) для запроса на создание нового счета-фактуры.
 *
 * <p>Используется для передачи данных от клиента (веб-интерфейс, другой сервис)
 * к контроллеру {@code InvoiceController} при создании нового инвойса.
 * Содержит минимальный набор полей, необходимых для инициализации счета.</p>
 *
 * <p>Данный DTO не содержит идентификаторов и системных полей (id, status, createdAt),
 * так как они генерируются автоматически на стороне сервера при создании
 * сущности {@link producer1.entity.Invoice}.</p>
 *
 * @author Andrus Gregory
 * @see producer1.controller.InvoiceController
 * @see producer1.entity.Invoice
 * @see producer1.service.InvoiceService
 */
@Data
public class CreateInvoiceRequest {
    /**
     * Номер счета, для которого создается счет.
     *
     * <p>Это обязательное поле, которое должно быть уникальным в рамках
     * системы учета клиентов. Используется для идентификации плательщика
     * и привязки счета к конкретному клиенту в биллинговой системе.</p>
     */
    private String accountNumber;

    /**
     * Сумма счета в базовой валюте системы.
     *
     * <p>Обязательное поле, определяющее финансовую сумму, которую должен
     * оплатить клиент. Должно быть строго положительным числом.</p>
     *
     * <p>Примеры:</p>
     * <ul>
     *   <li>{@code 1500.50} — одна тысяча пятьсот рублей 50 копеек</li>
     *   <li>{@code 99.99} — девяносто девять рублей 99 копеек</li>
     *   <li>{@code 1000000.00} — один миллион рублей</li>
     * </ul>
     */
    private Double amount;
}